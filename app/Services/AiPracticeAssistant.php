<?php

namespace App\Services;

use App\Models\Appointment;
use App\Models\Tenant;
use ImranDevBd\AiHub\Facades\AIHub;

class AiPracticeAssistant
{
    /**
     * Draft a professional, empathetic appointment reminder or follow-up email.
     */
    public function draftAppointmentMessage(Appointment $appointment, string $tone = 'empathetic'): string
    {
        $tenant = $appointment->tenant;
        if ($tenant && !$tenant->hasModule('ai_integration')) {
            throw new \RuntimeException("AI features are disabled for this organization.");
        }

        $serviceName = $appointment->service->name ?? 'counseling consultation';
        $scheduledTime = $appointment->scheduled_at->format('l, F j, Y \a\t g:i A');

        $prompt = <<<EOT
Draft a concise, warm, professional appointment reminder message for a mental health clinic.
Session: {$serviceName}
Scheduled: {$scheduledTime}
Tone: {$tone}
Safety Rules:
- Keep strictly administrative.
- Do not make clinical assumptions or diagnostic statements.
- Remind client that the clinic is not an emergency psychiatric service.
- If in crisis, call or text 988.
EOT;

        try {
            $response = AIHub::ask($prompt);
            return trim($response);
        } catch (\Throwable $e) {
            // Graceful fallback template
            return "Hello, this is a reminder for your upcoming session ({$serviceName}) on {$scheduledTime}. Please let us know at least 24 hours in advance if you need to reschedule. Note: Serenity Mental Wellness Center is not an emergency service. In an urgent mental health crisis, please dial 988.";
        }
    }

    /**
     * Draft an unapproved SOAP clinical note skeleton based on clinician-provided session raw observations.
     * Note: strictly requires human clinician review, approval and digital signing.
     */
    public function draftSoapNoteDraft(string $rawPractitionerObservations): array
    {
        $prompt = <<<EOT
You are an administrative clinical transcription assistant. Given the following practitioner raw observations, format them into standard structured SOAP sections.
STRICT SAFETY RULES:
- You are strictly an administrative formatter.
- Do NOT prescribe medication.
- Do NOT generate diagnoses without clinician notes.
- Do NOT replace licensed professional judgment.
Observations: "{$rawPractitionerObservations}"

Output a JSON object with keys:
- subjective: client's reported experiences and feelings
- objective: observable clinical affect, alertness, behavioral demeanor
- assessment: clinician's progress impression based strictly on observations
- plan: recommended follow-up homework or next scheduled appointment
EOT;

        try {
            $res = AIHub::ask($prompt);
            $parsed = json_decode($res, true);
            if (is_array($parsed) && isset($parsed['subjective'])) {
                $parsed['disclaimer'] = 'UNAPPROVED DRAFT: Generated by AI Assistant. Must be clinically reviewed and signed by licensed practitioner.';
                return $parsed;
            }
        } catch (\Throwable $e) {
            // Fallback structured draft
        }

        return [
            'subjective' => 'Client reported current symptom levels and response to weekly self-care practices.',
            'objective' => 'Client engaged cooperatively; speech normal in rate and rhythm; affect congruent with mood.',
            'assessment' => 'Client actively participating in therapeutic process and working toward established treatment milestones.',
            'plan' => 'Continue weekly appointments; client to maintain daily tracking log.',
            'disclaimer' => 'UNAPPROVED DRAFT: Generated by AI Assistant. Must be clinically reviewed and signed by licensed practitioner.',
        ];
    }
}
